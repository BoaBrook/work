    /**
     * 获取主类型文字描述
     * @param majorInt 主类型整数
     * @return 文字描述
     */
    public static String getMajorDescription(int majorInt) {
        String majorHex = String.format("0x%x", majorInt);
        return MAJOR_TYPE_MAP.getOrDefault(majorHex, "未知主类型(" + majorHex + ")");
    }

    /**
     * 获取子类型文字描述
     * @param majorInt 主类型整数
     * @param minorInt 子类型整数
     * @return 文字描述
     */
    public static String getMinorDescription(int majorInt, int minorInt) {
        String majorHex = String.format("0x%x", majorInt);
        String minorHex = String.format("0x%x", minorInt);
        
        Map<String, String> minorMap = MINOR_TYPE_MAP.get(majorHex);
        if (minorMap != null && minorMap.containsKey(minorHex)) {
            return minorMap.get(minorHex);
        }
        
        return "未知子类型(" + minorHex + ")";
    }
